"""
Competitor Intelligence Agent
=============================
Purpose:
    Maps competitive landscape, identifies incumbent vendors,
    evaluates positioning differentiation, and defines defensive moats.
"""

import os
import sys
from typing import Any, Dict, List, Optional

# Ensure backend root directory is in sys.path
_current_dir = os.path.dirname(os.path.abspath(__file__))
_backend_dir = os.path.abspath(os.path.join(_current_dir, "../.."))
if _backend_dir not in sys.path:
    sys.path.insert(0, _backend_dir)

from app.services.llm_service import LLMService, llm_service
from app.core.logging import logger


class CompetitorAgent:
    """
    Agent evaluating competitive moats, direct incumbents, and indirect substitutes.
    """

    def __init__(self, service: Optional[LLMService] = None):
        self.llm_service = service or llm_service

    def execute(
        self,
        extracted_idea: Dict[str, Any],
        search_snippets: Optional[List[Dict[str, Any]]] = None,
    ) -> Dict[str, Any]:
        """
        Synthesizes competitive landscape and moats using search context.
        """
        industry = extracted_idea.get("industry", "Technology")
        name = extracted_idea.get("startup_name", "Venture")
        logger.info(f"[CompetitorAgent] Mapping competitive landscape for '{name}' in '{industry}'")

        # Extract competitor names from web search snippets if available
        identified_names = []
        if search_snippets:
            for snippet in search_snippets[:3]:
                title = snippet.get("title", "")
                if ":" in title:
                    candidate = title.split(":")[0].strip()
                    if 3 < len(candidate) < 40 and not any(w in candidate.lower() for w in ["market", "overview", "competitive", "trend"]):
                        identified_names.append(candidate)

        if not identified_names:
            identified_names = [
                f"Legacy {industry} Enterprise Vendors (High license cost, complex setup)",
                "Horizontal AI Assistants (Lack dedicated domain workflows)",
                "Fragmented In-house Manual Tools (Current default status quo)",
            ]

        defensive_moats = [
            "Proprietary domain data feedback loops that improve model precision over time",
            "High user switching costs generated by cumulative saved progress and telemetry",
            "Significantly lower total cost of ownership and accelerated time-to-value",
        ]

        return {
            "competitors": identified_names,
            "defensive_moats": defensive_moats,
            "competitive_risk": "Moderate - Incumbents have capital but slower innovation velocity.",
        }


# Singleton instance
competitor_agent = CompetitorAgent()


if __name__ == "__main__":
    agent = CompetitorAgent()
    print("CompetitorAgent test:", agent.execute({"industry": "EdTech", "startup_name": "PrepAI"}))
